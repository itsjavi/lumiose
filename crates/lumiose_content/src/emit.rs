//! The `.stsx` module of a component that renders a parsed HTML tree statically.

use std::fmt::Write as _;

use html5ever::{Attribute, ns};

use crate::assets::Assets;
use crate::dom::{Data, Handle};
use crate::markdown::Heading;
use crate::{Component, Script};

/// Elements nested deeper than this are left out (no stack overflow on hostile input).
const MAX_DEPTH: usize = 512;

/// HTML elements without end tags.
const VOID: [&str; 18] = [
    "area", "base", "basefont", "bgsound", "br", "col", "embed", "frame", "hr", "img", "input",
    "keygen", "link", "meta", "param", "source", "track", "wbr",
];

/// HTML elements whose content is raw text (with scripting enabled, `<noscript>` too).
const RAW_TEXT: [&str; 8] = [
    "iframe",
    "noembed",
    "noframes",
    "noscript",
    "plaintext",
    "script",
    "style",
    "xmp",
];

/// Attribute names the compiler gives a meaning of its own: written through a spread object.
const RESERVED: [&str; 4] = ["key", "ref", "attach", "children"];

/// What a file contributes: top-level nodes, and whether it is Markdown (which exports
/// `frontmatter`).
pub(crate) struct Input<'a> {
    pub(crate) nodes: Vec<Handle>,
    /// The file's name (`post.md`), for the module's relative imports.
    pub(crate) name: &'a str,
    /// A Markdown file's headings (`None` for HTML).
    pub(crate) markdown: Option<Vec<Heading>>,
    pub(crate) frontmatter: Option<String>,
}

#[derive(Default)]
struct Emitter {
    /// Markdown drops `<script>` elements (an error, reported by the caller).
    markdown: bool,
    jsx: String,
    assets: Assets,
    /// File-level style blocks: (global, css).
    blocks: Vec<(bool, String)>,
    scripts: Vec<Script>,
}

pub(crate) fn module(input: Input) -> Component {
    let mut emitter = Emitter {
        markdown: input.markdown.is_some(),
        ..Emitter::default()
    };
    // Top-level blocks and scripts leave the markup; what is left is trimmed, and runs of
    // whitespace between the nodes they leave are kept once.
    let mut content: Vec<&Handle> = Vec::new();
    for node in &input.nodes {
        if let Some(css) = style_block(node) {
            emitter.blocks.push(css);
        } else if !emitter.take_script(node)
            && !(is_blank(node) && content.last().is_some_and(|last| is_blank(last)))
        {
            content.push(node);
        }
    }
    let start = content
        .iter()
        .position(|n| !is_blank(n))
        .unwrap_or(content.len());
    let end = content
        .iter()
        .rposition(|n| !is_blank(n))
        .map_or(start, |i| i + 1);
    for node in &content[start..end] {
        emitter.node(node, 3);
    }
    let Emitter {
        jsx,
        blocks,
        scripts,
        assets,
        ..
    } = emitter;

    let name = input.name;
    let mut out = format!(
        "// Generated by Lumiose from {name} (lumiose_content): a static component.\n",
        name = name.replace(['\n', '\r'], " ")
    );
    if let Some(headings) = &input.markdown {
        let _ = writeln!(
            out,
            "export {{ frontmatter }} from {};",
            js_string(&format!("./{name}?lumiose-frontmatter"))
        );
        out.push_str("export const headings = [");
        for (i, heading) in headings.iter().enumerate() {
            let _ = write!(
                out,
                "{}\n  {{ depth: {}, text: {}, id: {} }}",
                if i == 0 { "" } else { "," },
                heading.depth,
                js_string(&heading.text),
                js_string(&heading.id)
            );
        }
        out.push_str(if headings.is_empty() {
            "];\n"
        } else {
            "\n];\n"
        });
    }
    out.push_str(&assets.imports());
    if !scripts.is_empty() {
        // An island without props: pages load the scripts the way they load island modules.
        let _ = writeln!(
            out,
            "import {{ Script as LumioseScript }} from {};",
            js_string(&format!("./{name}?lumiose-script"))
        );
    }
    out.push_str("export default function Content() {\n  return (\n    <>\n");
    out.push_str(&jsx);
    if !scripts.is_empty() {
        out.push_str("      <LumioseScript client:load />\n");
    }
    out.push_str("    </>\n  );\n}\n");
    for (global, css) in blocks {
        let _ = write!(
            out,
            "\n<style{}>{}</style>\n",
            if global { " global" } else { "" },
            css
        );
    }
    Component {
        source: out,
        frontmatter: input.frontmatter,
        scripts,
        diagnostics: Vec::new(),
    }
}

/// Whitespace-only text, or a comment.
fn is_blank(node: &Handle) -> bool {
    match &node.data {
        Data::Text(text) => text.borrow().trim().is_empty(),
        Data::Inert => true,
        _ => false,
    }
}

pub(crate) fn is_client_script(node: &Handle) -> bool {
    script(node).is_some()
}

/// A client script: a `<script>` (HTML or SVG) of JavaScript.
fn script(node: &Handle) -> Option<Script> {
    let Data::Element { name, .. } = &node.data else {
        return None;
    };
    if &*name.local != "script"
        || !(name.ns == ns!(html) || name.ns == ns!(svg))
        || !is_javascript(node.attribute("type").as_deref())
    {
        return None;
    }
    Some(match node.attribute("src") {
        Some(src) => Script::Src(src),
        None => {
            let mut code = String::new();
            node.text_content(&mut code);
            Script::Inline(code)
        }
    })
}

/// A `<style>` element's block: (global, css).
fn style_block(node: &Handle) -> Option<(bool, String)> {
    (node.html_name()? == "style").then(|| {
        let mut css = String::new();
        node.text_content(&mut css);
        (node.attribute("global").is_some(), css)
    })
}

impl Emitter {
    fn node(&mut self, node: &Handle, depth: usize) {
        if depth > MAX_DEPTH {
            return;
        }
        let indent = "  ".repeat(depth);
        let (name, attrs) = match &node.data {
            Data::Text(text) => {
                let _ = writeln!(self.jsx, "{indent}{{{}}}", js_string(&text.borrow()));
                return;
            }
            Data::Element { name, attrs, .. } => (name, attrs.borrow()),
            Data::Document | Data::Inert => return,
        };
        let local: &str = &name.local;
        let html = name.ns == ns!(html);
        // Data blocks (JSON-LD, an import map…) stay in the markup, as raw text.
        if self.take_script(node) {
            return;
        }
        if !is_jsx_name(local) {
            // Not writable as JSX: its content stays.
            self.children(node, depth);
            return;
        }
        let _ = write!(self.jsx, "{indent}<{local}");
        if html && local == "style" {
            // A nested block: scoped to its enclosing element, like in `.stsx`.
            let mut css = String::new();
            node.text_content(&mut css);
            let global = if node.attribute("global").is_some() {
                " global"
            } else {
                ""
            };
            let _ = writeln!(self.jsx, "{global}>{css}</style>");
            return;
        }
        attributes(
            &mut self.jsx,
            &mut self.assets,
            html.then_some(local),
            &attrs,
        );
        if name.ns == ns!(svg) && local == "style" {
            // Native SVG CSS: raw text, which the `.stsx` scanner keeps verbatim. In a page an
            // inline SVG's `<style>` is read as markup, not raw text, so `<` and `&` become CSS
            // escapes (`\3c `, `\26 `), as in `lumiose_svg`: the same in strings and identifiers,
            // but they cannot open a tag or an entity (TASK-474).
            let mut css = String::new();
            node.text_content(&mut css);
            let css = css.replace('<', "\\3c ").replace('&', "\\26 ");
            let _ = writeln!(self.jsx, ">{css}</style>");
            return;
        }
        let verbatim = if let Data::Element {
            template: Some(contents),
            ..
        } = &node.data
        {
            // A template's content (a web component's shadow DOM) is left as it is.
            Some(serialize_children(contents, 0))
        } else if html && RAW_TEXT.contains(&local) {
            let mut text = String::new();
            node.text_content(&mut text);
            Some(text)
        } else {
            None
        };
        if let Some(html) = verbatim {
            if !html.is_empty() {
                let _ = write!(self.jsx, " innerHTML={{{}}}", js_string(&html));
            }
            self.jsx.push_str(" />\n");
            return;
        }
        if node.children.borrow().is_empty() || html && VOID.contains(&local) {
            self.jsx.push_str(" />\n");
            return;
        }
        self.jsx.push_str(">\n");
        // The parser drops a newline right after these start tags: keep the content's own.
        if html
            && matches!(local, "pre" | "textarea" | "listing")
            && let Some(first) = node.children.borrow().first()
            && let Data::Text(text) = &first.data
            && text.borrow().starts_with('\n')
        {
            let _ = writeln!(self.jsx, "{indent}  {{\"\\n\"}}");
        }
        self.children(node, depth);
        let _ = writeln!(self.jsx, "{indent}</{local}>");
    }

    /// Collects a client script (in Markdown, drops any `<script>`): whether `node` was one.
    fn take_script(&mut self, node: &Handle) -> bool {
        if self.markdown {
            return matches!(&node.data, Data::Element { name, .. } if &*name.local == "script");
        }
        script(node)
            .map(|script| self.scripts.push(script))
            .is_some()
    }

    fn children(&mut self, node: &Handle, depth: usize) {
        for child in node.children.borrow().iter() {
            self.node(child, depth + 1);
        }
    }
}

/// Writes ` name="value"` for each attribute, and a spread object for the names JSX cannot
/// write or the compiler reads itself (`@click`, `x-on:click.prevent`, `key`).
/// The relative URLs of an HTML `element`'s URL attributes are imported through `assets`.
fn attributes(out: &mut String, assets: &mut Assets, element: Option<&str>, attrs: &[Attribute]) {
    let mut spread = Vec::new();
    for attr in attrs {
        let local: &str = &attr.name.local;
        let name = match attr.name.ns {
            ns!() => local.to_owned(),
            ns!(xlink) => format!("xlink:{local}"),
            ns!(xml) => format!("xml:{local}"),
            // `xmlns` declarations: the namespace comes from the element.
            _ => continue,
        };
        let value: &str = &attr.value;
        if is_jsx_attribute(&name) {
            if let Some(expression) =
                element.and_then(|element| assets.expression(element, &name, value))
            {
                let _ = write!(out, " {name}={{{expression}}}");
            } else if value.contains(['"', '&', '\n', '\r']) {
                let _ = write!(out, " {name}={{{}}}", js_string(value));
            } else {
                let _ = write!(out, " {name}=\"{value}\"");
            }
        } else {
            spread.push(format!("{}: {}", js_string(&name), js_string(value)));
        }
    }
    if !spread.is_empty() {
        let _ = write!(out, " {{...{{ {} }}}}", spread.join(", "));
    }
}

/// Whether a `<script type>` is JavaScript (a classic script or a module).
fn is_javascript(kind: Option<&str>) -> bool {
    let Some(kind) = kind else {
        return true;
    };
    let kind = kind.trim().to_ascii_lowercase();
    kind.is_empty()
        || kind == "module"
        || kind.contains("javascript")
        || kind.contains("ecmascript")
        || kind.ends_with("/jscript")
        || kind.ends_with("/livescript")
}

/// An intrinsic element name JSX can write: `div`, `my-element`, `foreignObject`.
fn is_jsx_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '-')
}

/// An attribute name JSX can write and the compiler treats as a plain attribute.
fn is_jsx_attribute(name: &str) -> bool {
    let part = |part: &str| {
        let mut chars = part.chars();
        chars
            .next()
            .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    };
    let valid = match name.split_once(':') {
        Some((namespace, local)) => {
            part(namespace) && part(local) && !matches!(namespace, "client" | "on" | "bind")
        }
        None => part(name),
    };
    valid && !RESERVED.contains(&name)
}

/// The HTML serialization of `node`'s children (a template's content).
fn serialize_children(node: &Handle, depth: usize) -> String {
    let mut out = String::new();
    serialize_into(&mut out, node, depth);
    out
}

fn serialize_into(out: &mut String, node: &Handle, depth: usize) {
    if depth > MAX_DEPTH {
        return;
    }
    let raw = node
        .html_name()
        .is_some_and(|name| RAW_TEXT.contains(&name));
    for child in node.children.borrow().iter() {
        match &child.data {
            Data::Text(text) if raw => out.push_str(&text.borrow()),
            Data::Text(text) => escape(out, &text.borrow(), false),
            Data::Element {
                name,
                attrs,
                template,
                ..
            } => {
                let _ = write!(out, "<{}", qualified(name.prefix.as_deref(), &name.local));
                for attr in attrs.borrow().iter() {
                    let _ = write!(
                        out,
                        " {}=\"",
                        qualified(attr.name.prefix.as_deref(), &attr.name.local)
                    );
                    escape(out, &attr.value, true);
                    out.push('"');
                }
                out.push('>');
                if name.ns == ns!(html) && VOID.contains(&&*name.local) {
                    continue;
                }
                serialize_into(out, template.as_ref().unwrap_or(child), depth + 1);
                let _ = write!(out, "</{}>", qualified(name.prefix.as_deref(), &name.local));
            }
            Data::Document | Data::Inert => {}
        }
    }
}

fn qualified(prefix: Option<&str>, local: &str) -> String {
    match prefix {
        Some(prefix) => format!("{prefix}:{local}"),
        None => local.to_owned(),
    }
}

fn escape(out: &mut String, text: &str, attribute: bool) {
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '\u{a0}' => out.push_str("&nbsp;"),
            '"' if attribute => out.push_str("&quot;"),
            '<' if !attribute => out.push_str("&lt;"),
            '>' if !attribute => out.push_str("&gt;"),
            ch => out.push(ch),
        }
    }
}

/// A double-quoted JavaScript string literal.
pub(crate) fn js_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            ch if ch.is_control() => {
                let _ = write!(out, "\\u{:04x}", u32::from(ch));
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert!(is_jsx_name("div") && is_jsx_name("my-el") && is_jsx_name("foreignObject"));
        assert!(!is_jsx_name("My") && !is_jsx_name("a.b") && !is_jsx_name("x_y"));
        assert!(is_jsx_attribute("data-x") && is_jsx_attribute("xlink:href"));
        for name in [
            "@click",
            ":class",
            "x-on:click.prevent",
            "client:load",
            "key",
            "on:x",
        ] {
            assert!(!is_jsx_attribute(name), "{name}");
        }
    }

    #[test]
    fn script_types() {
        for kind in [None, Some(""), Some("module"), Some(" text/JavaScript ")] {
            assert!(is_javascript(kind), "{kind:?}");
        }
        for kind in [
            "application/ld+json",
            "importmap",
            "text/x-template",
            "speculationrules",
        ] {
            assert!(!is_javascript(Some(kind)), "{kind}");
        }
    }
}
