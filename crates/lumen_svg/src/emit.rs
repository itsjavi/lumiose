//! The component module for an (optimised) SVG document.

use std::fmt::Write as _;

use roxmltree::{Document, Node};

use crate::allow;
use crate::prefix::Prefixer;
use crate::{SvgError, parse_options, xml_error};

const SVG: &str = "http://www.w3.org/2000/svg";
const XML: &str = "http://www.w3.org/XML/1998/namespace";
const XLINK: &str = "http://www.w3.org/1999/xlink";

/// Elements whose text is content: their whitespace is kept.
const TEXT_CONTENT: [&str; 4] = ["text", "tspan", "textPath", "a"];

/// Elements nested deeper than this make the file an error (no stack overflow on hostile input,
/// here or in the compiler that compiles the component).
pub(crate) const MAX_DEPTH: usize = 128;

/// The `.stsx` module for `svg`; `prefix` makes its ids and the `<title>` id unique to the file.
pub(crate) fn component(svg: &str, prefix: &str) -> Result<String, SvgError> {
    // Before parsing: the XML parser recurses per nesting level too.
    check_source_depth(svg)?;
    let document = Document::parse_with_options(svg, parse_options()).map_err(|e| xml_error(&e))?;
    let root = svg_root(&document)?;
    check_depth(root)?;
    let prefixer = Prefixer::new(&document, prefix);

    let mut out = String::new();
    out.push_str(
        "// Generated by Lumen from an SVG file: an inline component whose props override the\n\
         // file's root attributes (lumen_svg).\n\
         export default function Svg({ title, children, ...rest }) {\n",
    );
    let _ = writeln!(
        out,
        "  const label = () =>\n    title == null || title === \"\" ? undefined : {} + String(title).replace(/\\s+/g, \"_\");",
        js_string(&format!("{prefix}-t-"))
    );
    out.push_str("  return (\n    <svg");
    for (name, value) in attributes(root, &prefixer) {
        let _ = write!(out, "\n      {}", attribute(&name, &value));
    }
    out.push_str(
        "\n      role={label() ? \"img\" : undefined}\
         \n      aria-labelledby={label()}\
         \n      aria-hidden={label() || rest[\"aria-label\"] || rest[\"aria-labelledby\"] ? undefined : \"true\"}\
         \n      {...rest}\
         \n    >\
         \n      {label() ? <title id={label()}>{title}</title> : null}\n",
    );
    for child in root.children() {
        node(&mut out, &prefixer, child, 3, false);
    }
    out.push_str("    </svg>\n  );\n}\n");
    Ok(out)
}

/// The `<svg>` root element of `document`.
pub(crate) fn svg_root<'a, 'input>(
    document: &'a Document<'input>,
) -> Result<Node<'a, 'input>, SvgError> {
    let root = document.root_element();
    if root.tag_name().name() == "svg" && matches!(root.tag_name().namespace(), None | Some(SVG)) {
        return Ok(root);
    }
    let name = root.tag_name().name();
    let message = match root.tag_name().namespace() {
        // `<x:svg xmlns:x="…">`: the right name in another namespace.
        Some(namespace) if name == "svg" => format!(
            "the root element is `<svg>` in the namespace `{namespace}`, expected the SVG \
             namespace `{SVG}`"
        ),
        _ => format!("the root element is `<{name}>`, expected `<svg>`"),
    };
    Err(SvgError {
        message,
        position: None,
    })
}

/// An error when the markup of `svg` nests elements deeper than [`MAX_DEPTH`], found with a scan
/// of its tags (comments, CDATA, processing instructions, declarations and quoted attribute values
/// skipped).
fn check_source_depth(svg: &str) -> Result<(), SvgError> {
    let bytes = svg.as_bytes();
    let mut depth = 0usize;
    let mut at = 0;
    let skip_to = |from: usize, end: &str| {
        svg[from..]
            .find(end)
            .map_or(svg.len(), |i| from + i + end.len())
    };
    while let Some(found) = svg[at..].find('<') {
        let start = at + found;
        let rest = &svg[start..];
        if rest.starts_with("<!--") {
            at = skip_to(start + 4, "-->");
        } else if rest.starts_with("<![CDATA[") {
            at = skip_to(start + 9, "]]>");
        } else if rest.starts_with("<?") {
            at = skip_to(start + 2, "?>");
        } else if rest.starts_with("<!") {
            at = skip_to(start + 2, ">");
        } else if rest.starts_with("</") {
            depth = depth.saturating_sub(1);
            at = skip_to(start + 2, ">");
        } else {
            // A start tag: to its `>`, outside quoted values.
            let mut i = start + 1;
            let mut quote = None;
            while i < bytes.len() {
                match (quote, bytes[i]) {
                    (None, b'"' | b'\'') => quote = Some(bytes[i]),
                    (Some(q), b) if b == q => quote = None,
                    (None, b'>') => break,
                    _ => {}
                }
                i += 1;
            }
            if i >= 1 && bytes.get(i.wrapping_sub(1)) != Some(&b'/') {
                depth += 1;
                if depth > MAX_DEPTH {
                    let line = svg[..start].matches('\n').count() + 1;
                    let column = start - svg[..start].rfind('\n').map_or(0, |n| n + 1) + 1;
                    return Err(SvgError {
                        message: format!("elements are nested deeper than {MAX_DEPTH} levels"),
                        position: Some((
                            u32::try_from(line).unwrap_or(u32::MAX),
                            u32::try_from(column).unwrap_or(u32::MAX),
                        )),
                    });
                }
            }
            at = (i + 1).min(svg.len());
        }
    }
    Ok(())
}

/// An error when elements nest deeper than [`MAX_DEPTH`].
fn check_depth(root: Node) -> Result<(), SvgError> {
    let mut stack = vec![(root, 1)];
    while let Some((node, depth)) = stack.pop() {
        if depth > MAX_DEPTH {
            let position = node.document().text_pos_at(node.range().start);
            return Err(SvgError {
                message: format!("elements are nested deeper than {MAX_DEPTH} levels"),
                position: Some((position.row, position.col)),
            });
        }
        stack.extend(
            node.children()
                .filter(Node::is_element)
                .map(|child| (child, depth + 1)),
        );
    }
    Ok(())
}

/// The attributes kept on an element, with their JSX names and prefixed ids: those of the
/// allowlist ([`allow::attribute`]), no `javascript:` URLs, no attributes of foreign namespaces;
/// `xlink:href` becomes `href` and `xlink:show` `target`, other XLink attributes are dropped.
fn attributes(element: Node, prefixer: &Prefixer) -> Vec<(String, String)> {
    let has = |name: &str| {
        element
            .attributes()
            .any(|a| a.namespace().is_none() && a.name() == name)
    };
    element
        .attributes()
        .filter_map(|attribute| {
            let local = attribute.name();
            let mut value = attribute.value().to_owned();
            let name = match attribute.namespace() {
                None => local.to_owned(),
                Some(XML) => format!("xml:{local}"),
                Some(XLINK) if local == "href" && !has("href") => "href".to_owned(),
                Some(XLINK) if local == "show" && !has("target") => {
                    value = match value.as_str() {
                        "new" => "_blank",
                        "replace" => "_self",
                        _ => return None,
                    }
                    .to_owned();
                    "target".to_owned()
                }
                Some(_) => return None,
            };
            (allow::attribute(&name) && !is_script_url(&value)).then(|| {
                let value = prefixer.attribute(&name, &value);
                (name, value)
            })
        })
        .collect()
}

/// Whether `value` is a `javascript:` URL, as a browser reads it: leading spaces and control
/// characters, and tabs or newlines inside the scheme, are ignored.
fn is_script_url(value: &str) -> bool {
    let mut scheme = value
        .trim_start_matches(|c: char| c <= ' ')
        .chars()
        .filter(|c| !matches!(c, '\t' | '\n' | '\r'));
    "javascript:".chars().all(|expected| {
        scheme
            .next()
            .is_some_and(|c| c.eq_ignore_ascii_case(&expected))
    })
}

/// Elements never emitted (with their content): those outside the allowlist ([`allow::element`]:
/// scripts, `<foreignObject>` and the HTML in it, unknown names), the file's own `<title>`
/// (`title` is a prop), and SMIL animations that could set a link or a handler.
fn dropped(element: Node) -> bool {
    let tag = element.tag_name();
    let name = tag.name();
    if !matches!(tag.namespace(), None | Some(SVG)) || !allow::element(name) || name == "title" {
        return true;
    }
    allow::ANIMATIONS.contains(&name) && unsafe_animation(element)
}

/// An animation of an `href`, of an event handler or of a `style` (`attributeName`, in any case,
/// as an HTML parser reads it), or one whose `values`/`from`/`to`/`by` hold a `javascript:` URL.
fn unsafe_animation(element: Node) -> bool {
    let value = |name: &str| {
        element
            .attributes()
            .find(|a| a.name().eq_ignore_ascii_case(name))
            .map(|a| a.value())
    };
    let target = value("attributeName")
        .unwrap_or_default()
        .trim()
        .to_ascii_lowercase();
    let target = target.rsplit(':').next().unwrap_or_default();
    target.ends_with("href")
        || target.starts_with("on")
        || target == "style"
        || ["values", "from", "to", "by"]
            .into_iter()
            .filter_map(value)
            .any(|text| text.split(';').any(is_script_url))
}

fn node(out: &mut String, prefixer: &Prefixer, node: Node, depth: usize, text_content: bool) {
    let indent = "  ".repeat(depth);
    if node.is_text() {
        let text = node.text().unwrap_or_default();
        if text_content || !text.trim().is_empty() {
            let _ = writeln!(out, "{indent}{{{}}}", js_string(text));
        }
        return;
    }
    if !node.is_element() {
        return;
    }
    let name = node.tag_name().name();
    if dropped(node) {
        return;
    }
    let _ = write!(out, "{indent}<{name}");
    for (attribute_name, value) in attributes(node, prefixer) {
        let _ = write!(out, " {}", self::attribute(&attribute_name, &value));
    }
    if !node.has_children() {
        out.push_str(" />\n");
        return;
    }
    if name == "style" {
        // Native SVG CSS: raw text, which the `.stsx` scanner keeps verbatim.
        let css: String = node.children().filter_map(|child| child.text()).collect();
        let css = prefixer.stylesheet(&css);
        let _ = writeln!(out, ">{}</style>", style_text(&css));
        return;
    }
    out.push_str(">\n");
    let text_content = text_content || TEXT_CONTENT.contains(&name);
    for child in node.children() {
        self::node(out, prefixer, child, depth + 1, text_content);
    }
    let _ = writeln!(out, "{indent}</{name}>");
}

/// CSS text for a `<style>` inside an inline `<svg>`, which an HTML parser reads as markup
/// (foreign content), not as raw text: `<` and `&` become CSS escapes (`\3c `, `\26 `), which mean
/// the same in strings and identifiers but cannot open a tag or an entity.
fn style_text(css: &str) -> String {
    css.replace('<', "\\3c ").replace('&', "\\26 ")
}

/// `name="value"`, or `name={"value"}` when a JSX string could not hold the value as is
/// (JSX decodes entities in attribute strings).
fn attribute(name: &str, value: &str) -> String {
    if value.contains(['"', '&', '\n', '\r']) {
        format!("{name}={{{}}}", js_string(value))
    } else {
        format!("{name}=\"{value}\"")
    }
}

/// A double-quoted JavaScript string literal.
fn js_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            ch if ch.is_control() => {
                let _ = write!(out, "\\u{:04x}", u32::from(ch));
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escapes_strings_and_attributes() {
        assert_eq!(js_string("a\"b\\c\nd\u{1}"), "\"a\\\"b\\\\c\\nd\\u0001\"");
        assert_eq!(js_string("\u{2028}\u{2029}"), "\"\\u2028\\u2029\"");
        assert_eq!(attribute("d", "M0 0h1"), r#"d="M0 0h1""#);
        assert_eq!(attribute("href", "a?b&c"), r#"href={"a?b&c"}"#);
    }

    #[test]
    fn drops_scripts_handlers_and_foreign_markup() {
        let svg = r#"<svg xmlns="http://www.w3.org/2000/svg" xmlns:x="urn:x" onload="alert(1)" x:a="1">
            <script>alert(1)</script>
            <a href=" JavaScript:alert(1)" onclick="alert(1)"><path d="M0 0"/></a>
            <x:meta/>
        </svg>"#;
        let source = component(svg, "lp").unwrap();
        for absent in ["alert", "onload", "onclick", "x:", "<meta"] {
            assert!(!source.contains(absent), "{absent} in\n{source}");
        }
        assert!(source.contains("<path d=\"M0 0\" />"), "{source}");
    }
}
