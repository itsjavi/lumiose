/// Whether an element keeps its place (with its subtree).
pub(crate) fn element(name: &str) -> bool {
    ELEMENTS.contains(&name)
}

/// Whether an attribute (its JSX name: `href`, `xml:space`) is kept.
pub(crate) fn attribute(name: &str) -> bool {
    ATTRIBUTES.contains(&name) || prefixed(name, "aria-") || prefixed(name, "data-")
}

/// `aria-label`, `data-icon`: the prefix, then lowercase letters, digits and `-`.
fn prefixed(name: &str, prefix: &str) -> bool {
    name.strip_prefix(prefix).is_some_and(|rest| {
        !rest.is_empty()
            && rest
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn allows_svg_names_in_their_case_only() {
        assert!(element("linearGradient") && element("feGaussianBlur") && element("textPath"));
        for name in [
            "lineargradient",
            "script",
            "foreignObject",
            "aNIMATE",
            "window.alert",
            "iframe",
        ] {
            assert!(!element(name), "{name}");
        }
        assert!(attribute("viewBox") && attribute("aria-label") && attribute("data-icon-x"));
        for name in [
            "viewbox",
            "onload",
            "innerHTML",
            "ref",
            "key",
            "on:click",
            "aria-",
            "data-X",
            "ATTRIBUTENAME",
            "srcdoc",
            "xmlns",
        ] {
            assert!(!attribute(name), "{name}");
        }
    }
}
