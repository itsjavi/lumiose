// The files @lumiose/adapter-netlify writes (./index.ts).

import { relative } from "node:path";

/** Where Netlify's Frameworks API reads functions from, relative to the project. */
export const FUNCTIONS_DIR = ".netlify/v1/functions";
export const FUNCTION_FILE = "lumiose-server.mjs";
/** The same server for form posts to prerendered pages, which their static files would refuse. */
export const ACTIONS_FUNCTION_FILE = "lumiose-actions.mjs";

/**
 * The `_headers` rule that caches the assets directory for a year: Vite names its files by content
 * hash (a file put in `public/<assetsDir>/` by hand gets it too).
 */
export function assetsCacheRule(base: string, assetsDir: string): string {
  const dir = assetsDir.replace(/^\/+|\/+$/g, "");
  return `${base}${dir}/*\n  cache-control: public, max-age=31536000, immutable\n`;
}

/**
 * The function module: the build's handler, with Netlify's context as `ctx.platform`, for every
 * path below `base` that no static file answers.
 */
export function functionCode(functionsDir: string, serverEntry: string, base: string): string {
  const paths = base === "/" ? ["/*"] : [base.slice(0, -1), `${base}*`];
  return module(functionsDir, serverEntry, {
    name: "Lumiose server",
    path: paths,
    preferStatic: true,
  });
}

/**
 * The function module for the form posts to the prerendered pages with actions (`paths`, with
 * `base`): Netlify would answer them from the page's static file (405), so this one, with the
 * same handler, takes their non-GET methods first.
 */
export function actionsFunctionCode(
  functionsDir: string,
  serverEntry: string,
  paths: readonly string[],
): string {
  return module(functionsDir, serverEntry, {
    name: "Lumiose form actions",
    path: [
      ...new Set(
        paths.flatMap((path) => [path, path.endsWith("/") ? path.slice(0, -1) || "/" : `${path}/`]),
      ),
    ],
    method: ["POST", "PUT", "PATCH", "DELETE"],
  });
}

function module(
  functionsDir: string,
  serverEntry: string,
  config: Record<string, unknown>,
): string {
  const specifier = relative(functionsDir, serverEntry).split("\\").join("/");
  return `// Generated by @lumiose/adapter-netlify: the server of the Lumiose build. Netlify serves the
// static files of dist/client first and calls it for the requests it routes here (config).
import handler from ${JSON.stringify(specifier.startsWith(".") ? specifier : `./${specifier}`)};

export default (request, context) =>
  handler.fetch(request, {
    waitUntil: (promise) => context.waitUntil(promise),
    clientAddress: context.ip,
  });

export const config = ${JSON.stringify({ ...config, generator: "@lumiose/adapter-netlify" }, null, 2)};
`;
}
