// The files @lumiose/adapter-cloudflare writes (./index.ts).

import { join, relative } from "node:path";
import type { AdapterBuild } from "@lumiose/vite/build";

/** The Worker, next to `dist/client` and `dist/server`. */
export const WORKER_FILE = "_worker.js";

const IMMUTABLE = "cache-control: public, max-age=31536000, immutable";

/**
 * The `_headers` rules that cache exactly the files the build named by content hash for a year:
 * the assets directory, with its other files (`public/<assetsDir>/` copies) detached
 * (`! cache-control`), plus any hashed file outside it. One rule in the common case: Cloudflare
 * reads at most 100.
 */
export function assetsCacheRules(
  build: Pick<AdapterBuild, "config" | "hashedFiles" | "unhashedAssets">,
): string {
  const { base, assetsDir } = build.config;
  const dir = assetsDir.replace(/^\/+|\/+$/g, "");
  let rules = `${base}${dir}/*\n  ${IMMUTABLE}\n`;
  for (const file of build.unhashedAssets) rules += `${base}${file}\n  ! cache-control\n`;
  for (const file of build.hashedFiles) {
    if (!file.startsWith(`${dir}/`)) rules += `${base}${file}\n  ${IMMUTABLE}\n`;
  }
  return rules;
}

/** `.assetsignore` lines for the prerendered pages with form actions (`""` when there are none). */
export function assetsIgnore(prerendered: AdapterBuild["prerendered"]): string {
  return prerendered
    .filter((file) => file.actions === true)
    .map((file) => `/${file.file}\n`)
    .join("");
}

/** The Worker module: the build's handler, with Cloudflare's arguments as `ctx.platform`. */
export function workerCode(outDir: string, serverEntry: string): string {
  const specifier = `./${relative(outDir, serverEntry).split("\\").join("/")}`;
  return `// Generated by @lumiose/adapter-cloudflare: the Worker. Cloudflare serves dist/client (the
// wrangler config's assets) and calls it for every other request.
import handler from ${JSON.stringify(specifier)};

export default {
  fetch(request, env, ctx) {
    return handler.fetch(request, {
      env,
      waitUntil: (promise) => ctx.waitUntil(promise),
      clientAddress: request.headers.get("cf-connecting-ip") ?? undefined,
    });
  },
};
`;
}

/** A starter wrangler.jsonc for the build: the Worker (if any), the assets and the flags. */
export function wranglerConfig(
  build: Pick<AdapterBuild, "root" | "outDir" | "clientDir" | "serverEntry" | "config">,
): string {
  const path = (file: string) => relative(build.root, file).split("\\").join("/");
  const htmlHandling = {
    ignore: "auto-trailing-slash",
    always: "force-trailing-slash",
    never: "drop-trailing-slash",
  }[build.config.trailingSlash];
  const lines = [
    "{",
    '  "name": "my-app",',
    ...(build.serverEntry === undefined
      ? []
      : [`  "main": ${JSON.stringify(path(join(build.outDir, WORKER_FILE)))},`]),
    '  "compatibility_date": "2026-09-01",',
    '  "compatibility_flags": ["nodejs_compat"],',
    `  "assets": { "directory": ${JSON.stringify(path(build.clientDir))}, "html_handling": ${JSON.stringify(htmlHandling)} }`,
    "}",
  ];
  return lines.join("\n");
}
