// `lumiose({ headers })` (decision-26 §4): response headers declared once, applied by `lumiose dev`,
// `lumiose preview` and @lumiose/adapter-node, and written to `dist/client/_headers` for static hosts.
// Paths are URL patterns below Vite's `base`: `*` matches one segment, `**` any number of them
// (none included). Headers that middleware, endpoints or `setHeader` set win over these.

/** A record applied to every response, or rules applied to the responses whose path matches. */
export type HeadersOption = Readonly<Record<string, string>> | readonly HeaderRule[];

export interface HeaderRule {
  /** URL pattern below `base`: `/assets/**`, `/blog/*`, `/about`. */
  path: string;
  headers: Readonly<Record<string, string>>;
}

/** The rules of a `headers` option; the record form is one rule for every path. */
export function headerRules(option: HeadersOption): readonly HeaderRule[] {
  return Array.isArray(option)
    ? option
    : [{ path: "/**", headers: option as Readonly<Record<string, string>> }];
}

/**
 * Sent on every response unless `lumiose({ headers })` gives them another value, or `""` to remove
 * them (decision-29, as Rails and Django do).
 */
export const DEFAULT_HEADERS: Readonly<Record<string, string>> = {
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
};

/** The default headers' rule followed by the rules of `option`. */
function effectiveRules(option: HeadersOption | undefined): readonly HeaderRule[] {
  return [
    { path: "/**", headers: DEFAULT_HEADERS },
    ...(option === undefined ? [] : headerRules(option)),
  ];
}

/**
 * The headers of a path below `base` (`/blog/a`): the defaults, then the configured rules in rule
 * order (a later rule's value of the same header wins). A header whose value is `""` is left out.
 */
export function headersFor(
  option: HeadersOption | undefined,
  pathname: string,
): Record<string, string> {
  const result: Record<string, string> = {};
  const path = segments(pathname);
  for (const rule of effectiveRules(option)) {
    if (!matches(segments(rule.path), path)) continue;
    for (const [name, value] of Object.entries(rule.headers)) result[name.toLowerCase()] = value;
  }
  for (const [name, value] of Object.entries(result)) if (value === "") delete result[name];
  return result;
}

function segments(path: string): string[] {
  return path.split("/").filter((segment) => segment !== "");
}

function matches(pattern: readonly string[], path: readonly string[]): boolean {
  if (pattern.length === 0) return path.length === 0;
  const [head, ...rest] = pattern;
  if (head === "**") {
    for (let i = 0; i <= path.length; i++) if (matches(rest, path.slice(i))) return true;
    return false;
  }
  if (path.length === 0) return false;
  return (head === "*" || head === path[0]) && matches(rest, path.slice(1));
}

/** The path of a request URL below `base` (`/sub/a?x` → `/a`); undefined outside it. */
export function pathBelowBase(url: string, base: string): string | undefined {
  // The pathname the router sees: dot segments resolved, so `/x/../admin` matches `/admin` rules
  // (TASK-167 L1).
  const pathname = decodeURIComponentSafe(normalizePath(url.split(/[?#]/, 1)[0]!));
  if (base === "/" || base === "" || base === "./") return pathname;
  const prefix = base.endsWith("/") ? base.slice(0, -1) : base;
  if (pathname === prefix) return "/";
  return pathname.startsWith(`${prefix}/`) ? pathname.slice(prefix.length) : undefined;
}

function normalizePath(path: string): string {
  try {
    return new URL(`http://localhost${path.startsWith("/") ? path : `/${path}`}`).pathname;
  } catch {
    return path;
  }
}

function decodeURIComponentSafe(path: string): string {
  try {
    return decodeURIComponent(path);
  } catch {
    return path;
  }
}

/**
 * The `_headers` file of static hosts (Netlify, Cloudflare Pages and Workers) for `option`, with
 * `base` prefixed to each path. `**` becomes the hosts' `*` splat; a `*` segment becomes a `:name`
 * placeholder (Cloudflare; Netlify matches it literally). Rules of the same path are one block
 * (a later value wins), as Cloudflare keeps only the last block of a path.
 */
export function headersFile(option: HeadersOption | undefined, base: string): string {
  const prefix = base.endsWith("/") ? base.slice(0, -1) : base;
  const blocks = new Map<string, Map<string, string>>();
  for (const rule of effectiveRules(option)) {
    let placeholder = 0;
    const path = segments(rule.path).map((segment) =>
      segment === "**" ? "*" : segment === "*" ? `:p${placeholder++}` : segment,
    );
    const key = `${prefix}/${path.join("/")}`;
    let block = blocks.get(key);
    if (block === undefined) blocks.set(key, (block = new Map()));
    for (const [name, value] of Object.entries(rule.headers)) block.set(name.toLowerCase(), value);
  }
  let text = "# Generated by lumiose build: Lumiose's default headers and lumiose({ headers }).\n";
  for (const [path, headers] of blocks) {
    text += `${path}\n`;
    for (const [name, value] of headers) {
      // `""` removes a header: static hosts' `! name` syntax (Netlify, Cloudflare).
      text += value === "" ? `  ! ${name}\n` : `  ${name}: ${value}\n`;
    }
  }
  return text;
}
