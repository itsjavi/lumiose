// The function of a Lumiose build on Vercel (`.vercel/output/functions/__lumiose.func`):
//
// - `nodejs`: a Node.js `(req, res)` handler (lumiose/node's bridge, bundled) around the build's
//   fetch handler, next to `dist/server/entry.js`, then every file it needs, traced with
//   @vercel/nft (the npm packages it imports included), copied into the function directory with
//   their paths below a common ancestor. Symbolic links (pnpm's node_modules) stay links.
// - `edge`: one ES module with everything bundled (npm packages resolved with the `edge-light` and
//   `worker` conditions); only the Node.js modules Vercel's Edge runtime provides may stay imports.

import { copyFile, lstat, mkdir, realpath, rm, symlink, writeFile } from "node:fs/promises";
import { dirname, join, parse, relative, resolve, sep } from "node:path";
import type { AdapterBuild } from "@lumiose/vite/build";

export type Runtime = "nodejs" | "edge";

/** Node.js modules the Edge runtime provides (with or without the `node:` prefix). */
export const EDGE_NODE_MODULES = ["async_hooks", "buffer", "events", "util", "assert"];

/** The `.vc-config.json` of a function. */
export type FunctionConfig =
  | {
      runtime: string;
      handler: string;
      launcherType: "Nodejs";
      supportsResponseStreaming: true;
    }
  | { runtime: "edge"; entrypoint: string };

/** The Node.js runtime of the function: the build's major version, 22 at least. */
export function nodeRuntime(version: string = process.versions.node): string {
  const major = Number(version.split(".")[0]);
  return major >= 24 ? "nodejs24.x" : "nodejs22.x";
}

/** The source of the Node.js handler, next to the entry (`./entry.js`). */
export function nodeHandlerCode(): string {
  return `// Generated by @lumiose/adapter-vercel: the Vercel Function, a Node.js (req, res) handler.
import { RejectedRequest, sendWebResponse, toWebRequest } from "lumiose/node";
import handler from "./entry.js";

const requestContext = Symbol.for("@vercel/request-context");

export default async function lumiose(req, res) {
  let request;
  try {
    // Vercel's proxy terminates TLS: the public origin is in the forwarded headers.
    const proto = header(req, "x-forwarded-proto") ?? "https";
    const host = header(req, "x-forwarded-host") ?? header(req, "host");
    request = toWebRequest(req, res, host === undefined ? undefined : proto + "://" + host);
  } catch (error) {
    if (!(error instanceof RejectedRequest)) throw error;
    res.writeHead(error.status, { "content-type": "text/plain; charset=utf-8" });
    res.end(error.message);
    return;
  }
  const waitUntil = globalThis[requestContext]?.get?.()?.waitUntil;
  const response = await handler.fetch(request, {
    clientAddress: header(req, "x-real-ip") ?? req.socket.remoteAddress,
    ...(typeof waitUntil === "function" ? { waitUntil } : {}),
  });
  await sendWebResponse(res, response);
}

function header(req, name) {
  const value = req.headers[name];
  return (Array.isArray(value) ? value[0] : value)?.split(",")[0].trim() || undefined;
}
`;
}

/** The source of the Edge function, importing the entry by `entry` (an absolute path). */
export function edgeHandlerCode(entry: string): string {
  return `// Generated by @lumiose/adapter-vercel: the Vercel Edge Function.
import handler from ${JSON.stringify(entry.split(sep).join("/"))};

export default (request, context) =>
  handler.fetch(request, {
    waitUntil: (promise) => context.waitUntil(promise),
    clientAddress: request.headers.get("x-real-ip") ?? undefined,
  });
`;
}

/** Bundles `input` into `outDir/fileName` with Vite: the build's own config is not loaded. */
async function bundle(
  build: AdapterBuild,
  input: string,
  outDir: string,
  fileName: string,
  runtime: Runtime,
): Promise<string[]> {
  const { build: viteBuild } = await import("vite");
  const entry = runtime === "nodejs" ? resolve(dirname(input), "entry.js") : undefined;
  const output = await viteBuild({
    configFile: false,
    root: build.root,
    mode: build.mode,
    logLevel: "warn",
    // The build is done: no public dir, no .env files for a bundle of built code.
    publicDir: false,
    envDir: false,
    resolve:
      runtime === "edge"
        ? { conditions: ["edge-light", "worker", "module", "import", "default"] }
        : {},
    // Edge: everything bundled for a web worker (no `createRequire` for CommonJS packages); the
    // Node.js modules it imports stay imports, checked below.
    ssr: runtime === "edge" ? { noExternal: true, target: "webworker" } : {},
    build: {
      ssr: input,
      outDir,
      emptyOutDir: false,
      copyPublicDir: false,
      minify: false,
      rolldownOptions: {
        // Node.js: the entry and its chunks stay as they are; only lumiose/node is bundled in.
        external:
          entry === undefined
            ? (id: string) => id.startsWith("node:")
            : (id: string) => resolve(dirname(input), id) === entry,
        output: {
          entryFileNames: fileName,
          ...(runtime === "edge" ? { codeSplitting: false } : {}),
        },
      },
    },
  });
  const outputs = (Array.isArray(output) ? output : [output]) as Array<{
    output: Array<{
      type: string;
      fileName: string;
      imports?: string[];
      dynamicImports?: string[];
    }>;
  }>;
  const chunks = outputs.flatMap(({ output: files }) =>
    files.filter((file) => file.type === "chunk"),
  );
  const own = new Set(chunks.map((chunk) => chunk.fileName));
  const imports = new Set<string>();
  for (const chunk of chunks) {
    for (const id of [...(chunk.imports ?? []), ...(chunk.dynamicImports ?? [])]) {
      if (!own.has(id)) imports.add(id);
    }
  }
  return [...imports];
}

/**
 * Writes the Node.js function into `funcDir`: the handler next to the build's entry, traced with
 * @vercel/nft and copied with its dependencies. Returns the function's config.
 */
export async function nodeFunction(build: AdapterBuild, funcDir: string): Promise<FunctionConfig> {
  const serverDir = dirname(build.serverEntry!);
  const source = join(serverDir, "vercel-handler.src.js");
  const handler = join(serverDir, "vercel-handler.js");
  await writeFile(source, nodeHandlerCode());
  try {
    await bundle(build, source, serverDir, "vercel-handler.js", "nodejs");
  } finally {
    await rm(source, { force: true });
  }
  const { nodeFileTrace } = await import("@vercel/nft");
  const fsRoot = parse(build.root).root;
  const traced = await nodeFileTrace([handler], { base: fsRoot, processCwd: build.root });
  const files = [...traced.fileList].map((file) => join(fsRoot, file));
  // The project's package.json carries `"type": "module"` for the build's `.js` files.
  const manifest = join(build.root, "package.json");
  if (!files.includes(manifest)) files.push(manifest);
  const reals = await Promise.all(files.map((file) => realpath(file)));
  const ancestor = commonAncestor([...files, ...reals].map((file) => dirname(file)));
  for (const file of files) {
    const dest = join(funcDir, relative(ancestor, file));
    await mkdir(dirname(dest), { recursive: true });
    const stats = await lstat(file);
    if (stats.isSymbolicLink()) {
      // pnpm links node_modules/<name> to its store: the same link, inside the function.
      const target = join(funcDir, relative(ancestor, await realpath(file)));
      await rm(dest, { force: true, recursive: true });
      await symlink(relative(dirname(dest), target), dest);
    } else if (stats.isFile()) {
      await copyFile(file, dest);
    }
  }
  return {
    runtime: nodeRuntime(),
    handler: relative(ancestor, handler).split(sep).join("/"),
    launcherType: "Nodejs",
    supportsResponseStreaming: true,
  };
}

/** Writes the Edge function into `funcDir`: one bundled module. Returns the function's config. */
export async function edgeFunction(build: AdapterBuild, funcDir: string): Promise<FunctionConfig> {
  const source = join(funcDir, "edge.src.js");
  await mkdir(funcDir, { recursive: true });
  await writeFile(source, edgeHandlerCode(build.serverEntry!));
  let imports: string[];
  try {
    imports = await bundle(build, source, funcDir, "index.js", "edge");
  } finally {
    await rm(source, { force: true });
  }
  const unsupported = imports.filter((id) => !EDGE_NODE_MODULES.includes(id.replace(/^node:/, "")));
  if (unsupported.length > 0) {
    throw new Error(
      `@lumiose/adapter-vercel: the Edge runtime cannot import ${unsupported.map((id) => JSON.stringify(id)).join(", ")} (from the server code or its npm packages). Use vercel({ runtime: "nodejs" }), or remove those imports.`,
    );
  }
  return { runtime: "edge", entrypoint: "index.js" };
}

/** The deepest directory containing every one of `dirs`. */
export function commonAncestor(dirs: readonly string[]): string {
  let ancestor = dirs[0]!;
  for (const dir of dirs) {
    while (
      dir !== ancestor &&
      !dir.startsWith(ancestor.endsWith(sep) ? ancestor : ancestor + sep)
    ) {
      ancestor = dirname(ancestor);
    }
  }
  return ancestor;
}
