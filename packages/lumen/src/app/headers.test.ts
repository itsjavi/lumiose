// `lumen({ headers })` matching and the `_headers` file (TASK-125, decision-26 §4).
import { describe, expect, it } from "vitest";
import { headersFile, headersFor, type HeaderRule } from "./headers.ts";

describe("headersFor()", () => {
  it("applies a record to every path", () => {
    const option = { "Cross-Origin-Opener-Policy": "same-origin" };
    expect(headersFor(option, "/")).toEqual({ "cross-origin-opener-policy": "same-origin" });
    expect(headersFor(option, "/songs/1")).toEqual({ "cross-origin-opener-policy": "same-origin" });
  });

  it("matches * as one segment and ** as any depth; later rules win", () => {
    const option: HeaderRule[] = [
      { path: "/**", headers: { "x-a": "all" } },
      { path: "/blog/*", headers: { "x-b": "post" } },
      { path: "/assets/**", headers: { "x-a": "asset" } },
      { path: "/about", headers: { "x-c": "about" } },
    ];
    expect(headersFor(option, "/")).toEqual({ "x-a": "all" });
    expect(headersFor(option, "/blog/hello")).toEqual({ "x-a": "all", "x-b": "post" });
    expect(headersFor(option, "/blog")).toEqual({ "x-a": "all" });
    expect(headersFor(option, "/blog/a/b")).toEqual({ "x-a": "all" });
    expect(headersFor(option, "/assets/x/y.js")).toEqual({ "x-a": "asset" });
    expect(headersFor(option, "/about/")).toEqual({ "x-a": "all", "x-c": "about" });
  });
});

describe("headersFile()", () => {
  it("writes the static hosts' _headers format below base", () => {
    expect(headersFile({ "x-a": "1" }, "/")).toBe(
      "# Generated by lumen build from lumen({ headers }).\n/*\n  x-a: 1\n",
    );
    expect(
      headersFile([{ path: "/blog/*/**", headers: { "x-b": "2", "x-c": "3" } }], "/sub/"),
    ).toBe(
      "# Generated by lumen build from lumen({ headers }).\n/sub/blog/:p0/*\n  x-b: 2\n  x-c: 3\n",
    );
  });
});
