// Generates `.lumen/types/routes.d.ts`: augments the `RouteMap` registry in "lumen" so
// `Routes`, `RouteParams`, `RouteProps` and `href()` know every route pattern.

import type { RouteManifest } from "../routes/manifest.ts";

export function generateRouteTypes(manifest: Pick<RouteManifest, "routes" | "routesDir">): string {
  const entries = manifest.routes
    .toSorted((a, b) => (a.pattern < b.pattern ? -1 : a.pattern > b.pattern ? 1 : 0))
    .map((route) => {
      const params = route.params.map((param) => `${param.name}: string`).join("; ");
      return `    ${JSON.stringify(route.pattern)}: { kind: "${route.kind}"; params: {${params === "" ? "" : ` ${params} `}} };`;
    });
  return [
    `// Generated by Lumen from ${manifest.routesDir}. Do not edit: \`lumen typegen\` rewrites it.`,
    "export {};",
    "",
    'declare module "lumen" {',
    "  interface RouteMap {",
    ...entries,
    "  }",
    "}",
    "",
  ].join("\n");
}
