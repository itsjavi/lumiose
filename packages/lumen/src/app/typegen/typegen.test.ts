import { execFile } from "node:child_process";
import { cp, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createRouteManifest } from "../routes/manifest.ts";
import { generateRouteTypes, ROUTE_TYPES_FILE, typegen } from "./index.ts";

const BASIC = fileURLToPath(new URL("../routes/__fixtures__/basic", import.meta.url));
const LUMEN_ENTRY = fileURLToPath(new URL("../../index.ts", import.meta.url));
const BASE_TSCONFIG = fileURLToPath(new URL("../../../../../tsconfig.base.json", import.meta.url));
const TSC = join(
  dirname(createRequire(import.meta.url).resolve("typescript/package.json")),
  "bin/tsc",
);

describe("generateRouteTypes", () => {
  it("augments the lumen RouteMap and LayoutMap with every route and layout, sorted by pattern", () => {
    const manifest = createRouteManifest([
      { path: "_layout.stsx", source: "" },
      { path: "(shop)/_layout.stsx", source: "" },
      { path: "shop/[category]/_layout.stsx", source: "" },
      { path: "index.stsx", source: "" },
      { path: "blog/[slug].stsx", source: "" },
      { path: "shop/[category]/[item].stsx", source: "" },
      { path: "docs/[...path].stsx", source: "" },
      { path: "sitemap.xml.ts", source: "" },
    ]);
    expect(generateRouteTypes(manifest)).toBe(
      [
        "// Generated by Lumen from src/routes. Do not edit: `lumen typegen` rewrites it.",
        "export {};",
        "",
        'declare module "lumen" {',
        "  interface RouteMap {",
        `    "/": { kind: "page"; params: {} };`,
        `    "/blog/[slug]": { kind: "page"; params: { slug: string } };`,
        `    "/docs/[...path]": { kind: "page"; params: { path: string } };`,
        `    "/shop/[category]/[item]": { kind: "page"; params: { category: string; item: string } };`,
        `    "/sitemap.xml": { kind: "endpoint"; params: {} };`,
        "  }",
        "  interface LayoutMap {",
        `    "/": { params: {} };`,
        `    "/shop/[category]": { params: { category: string } };`,
        "  }",
        "}",
        "",
      ].join("\n"),
    );
  });
});

describe("typegen", () => {
  let root: string;

  beforeAll(async () => {
    root = await mkdtemp(join(tmpdir(), "lumen-typegen-"));
    await cp(join(BASIC, "src"), join(root, "src"), { recursive: true });
  });

  afterAll(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it("writes .lumen/types/routes.d.ts and skips unchanged rewrites", async () => {
    const first = await typegen(root);
    expect(first.file).toBe(join(root, ROUTE_TYPES_FILE));
    expect(first.changed).toBe(true);
    expect(await readFile(first.file, "utf8")).toBe(generateRouteTypes(first.manifest));
    expect((await typegen(root)).changed).toBe(false);
  });

  it("type-checks typed routes, params and href() with TypeScript 7", async () => {
    await typegen(root);
    await writeFile(
      join(root, "tsconfig.json"),
      JSON.stringify({
        extends: BASE_TSCONFIG,
        compilerOptions: { types: [], paths: { lumen: [LUMEN_ENTRY] } },
        include: ["usage.ts", ".lumen/types"],
      }),
    );
    await writeFile(join(root, "usage.ts"), USAGE);
    const result = await promisify(execFile)(process.execPath, [
      TSC,
      "-p",
      root,
      "--pretty",
      "false",
    ]).then(
      () => ({ ok: true, output: "" }),
      (error: { stdout?: string; stderr?: string }) => ({
        ok: false,
        output: `${error.stdout ?? ""}${error.stderr ?? ""}`,
      }),
    );
    expect(result.output).toBe("");
    expect(result.ok).toBe(true);
  });
});

