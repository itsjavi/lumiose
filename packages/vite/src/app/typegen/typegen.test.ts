import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { resolveI18n } from "lumiose/internal/app/i18n/config.ts";
import { createRouteManifest } from "lumiose/internal/app/routes/manifest.ts";
import { generateRouteTypes, ROUTE_TYPES_FILE, typegen } from "./index.ts";

const BASIC = fileURLToPath(
  new URL("../../../../lumiose/src/app/routes/__fixtures__/basic", import.meta.url),
);
const LUMIOSE_ENTRY = fileURLToPath(new URL("../../../../lumiose/src/index.ts", import.meta.url));
const BASE_TSCONFIG = fileURLToPath(new URL("../../../../../tsconfig.base.json", import.meta.url));
const TSC = join(
  dirname(createRequire(import.meta.url).resolve("typescript/package.json")),
  "bin/tsc",
);

describe("generateRouteTypes", () => {
  it("augments the lumiose RouteMap and LayoutMap with every route and layout, sorted by pattern", () => {
    const manifest = createRouteManifest([
      { path: "layout.stsx", source: "" },
      { path: "(shop)/layout.stsx", source: "" },
      { path: "shop/[category]/layout.stsx", source: "" },
      { path: "[[lang]]/guide/layout.stsx", source: "" },
      { path: "page.stsx", source: "" },
      { path: "blog/[slug]/page.stsx", source: "" },
      { path: "shop/[category]/[item]/page.stsx", source: "" },
      { path: "docs/[...path]/page.stsx", source: "" },
      { path: "[[lang]]/guide/[[...path]]/page.stsx", source: "" },
      { path: "sitemap.xml/route.ts", source: "" },
    ]);
    expect(generateRouteTypes(manifest)).toBe(
      [
        "// Generated by Lumiose from src/routes. Do not edit: `lumiose typegen` rewrites it.",
        "export {};",
        "",
        'declare module "lumiose" {',
        "  interface RouteMap {",
        `    "/": { kind: "page"; params: {} };`,
        `    "/[[lang]]/guide/[[...path]]": { kind: "page"; params: { lang?: string; path?: string } };`,
        `    "/blog/[slug]": { kind: "page"; params: { slug: string } };`,
        `    "/docs/[...path]": { kind: "page"; params: { path: string } };`,
        `    "/shop/[category]/[item]": { kind: "page"; params: { category: string; item: string } };`,
        `    "/sitemap.xml": { kind: "endpoint"; params: {} };`,
        "  }",
        "  interface LayoutMap {",
        `    "/": { params: {} };`,
        `    "/[[lang]]/guide": { params: { lang?: string } };`,
        `    "/shop/[category]": { params: { category: string } };`,
        "  }",
        "}",
        "",
      ].join("\n"),
    );
  });
});

describe("generateRouteTypes with folder middleware", () => {
  it("lists folders that have only a middleware file in LayoutMap (decision-48)", () => {
    const manifest = createRouteManifest([
      { path: "layout.stsx", source: "" },
      { path: "admin/middleware.ts", source: "" },
      { path: "admin/users/[id]/page.stsx", source: "" },
      { path: "(account)/middleware.ts", source: "" },
      { path: "(account)/settings/page.stsx", source: "" },
    ]);
    expect(generateRouteTypes(manifest)).toContain(
      [
        "  interface LayoutMap {",
        `    "/": { params: {} };`,
        `    "/admin": { params: {} };`,
        "  }",
      ].join("\n"),
    );
  });
});

describe("typegen", () => {
  let root: string;

  beforeAll(async () => {
    root = await mkdtemp(join(tmpdir(), "lumiose-typegen-"));
    await cp(join(BASIC, "src"), join(root, "src"), { recursive: true });
    const optional = join(root, "src/routes/[[lang]]/guide/[[...path]]");
    await mkdir(optional, { recursive: true });
    await writeFile(join(optional, "page.stsx"), "export default function Guide() {}\n");
  });

  afterAll(async () => {
    await rm(root, { recursive: true, force: true });
  });

  it("writes .lumiose/types/routes.d.ts and skips unchanged rewrites", async () => {
    const first = await typegen(root);
    expect(first.file).toBe(join(root, ROUTE_TYPES_FILE));
    expect(first.changed).toBe(true);
    expect(await readFile(first.file, "utf8")).toBe(generateRouteTypes(first.manifest));
    expect((await typegen(root)).changed).toBe(false);
  });

  it("type-checks typed routes, params and href() with TypeScript 7", async () => {
    await typegen(root);
    await writeFile(
      join(root, "tsconfig.json"),
      JSON.stringify({
        extends: BASE_TSCONFIG,
        compilerOptions: { types: [], paths: { lumiose: [LUMIOSE_ENTRY] } },
        include: ["usage.ts", ".lumiose/types"],
      }),
    );
    await writeFile(join(root, "usage.ts"), USAGE);
    const result = await promisify(execFile)(process.execPath, [
      TSC,
      "-p",
      root,
      "--pretty",
      "false",
    ]).then(
      () => ({ ok: true, output: "" }),
      (error: { stdout?: string; stderr?: string }) => ({
        ok: false,
        output: `${error.stdout ?? ""}${error.stderr ?? ""}`,
      }),
    );
    expect(result.output).toBe("");
    expect(result.ok).toBe(true);
  });

  it("types ctx.params and ctx.route of folder middleware (decision-48)", async () => {
    const folder = join(root, "src/routes/shop/[category]");
    await writeFile(join(folder, "middleware.ts"), "export default [];\n");
    try {
      const { manifest } = await typegen(root);
      expect(manifest.diagnostics.filter((d) => d.severity === "error")).toEqual([]);
      await writeFile(join(root, "usage.ts"), MIDDLEWARE_USAGE);
      const result = await promisify(execFile)(process.execPath, [
        TSC,
        "-p",
        root,
        "--pretty",
        "false",
      ]).then(
        () => ({ ok: true, output: "" }),
        (error: { stdout?: string; stderr?: string }) => ({
          ok: false,
          output: `${error.stdout ?? ""}${error.stderr ?? ""}`,
        }),
      );
      expect(result.output).toBe("");
      expect(result.ok).toBe(true);
    } finally {
      await rm(join(folder, "middleware.ts"));
      await typegen(root);
    }
  });

  it("generates the Locale type of lumiose({ i18n }), which href() and the APIs take", async () => {
    const i18n = resolveI18n({ locales: ["en", "es"], defaultLocale: "en" });
    const { manifest } = await typegen(root, { i18n });
    const types = generateRouteTypes(manifest);
    expect(types).toContain(`  interface LocaleMap {\n    "en": true;\n    "es": true;\n  }\n`);
    await writeFile(join(root, "usage.ts"), LOCALE_USAGE);
    const result = await promisify(execFile)(process.execPath, [
      TSC,
      "-p",
      root,
      "--pretty",
      "false",
    ]).then(
      () => ({ ok: true, output: "" }),
      (error: { stdout?: string; stderr?: string }) => ({
        ok: false,
        output: `${error.stdout ?? ""}${error.stderr ?? ""}`,
      }),
    );
    expect(result.output).toBe("");
    expect(result.ok).toBe(true);
    await typegen(root);
  });
});

const LOCALE_USAGE = `import { alternates, href, locale, type Locale, type RequestContext } from "lumiose";

type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;
export type Assert<T extends true> = T;

export type Locales = Assert<Equal<Locale, "en" | "es">>;
export type FromContext = Assert<Equal<RequestContext["locale"], Locale>>;
export type FromLocale = Assert<Equal<ReturnType<typeof locale>, Locale>>;
export const current: Locale = locale();
export const links: { locale: Locale; href: string }[] = alternates();
export const about: { locale: Locale; href: string }[] = alternates("/about");
export const post: { locale: Locale; href: string }[] = alternates("/blog/[slug]", { slug: "a" });
// @ts-expect-error params are required
alternates("/blog/[slug]");
// @ts-expect-error unknown route
alternates("/abuot");
// @ts-expect-error locale is no param: alternates() lists every declared locale
alternates("/blog/[slug]", { slug: "a", locale: "es" });
export const urls: string[] = [
  href("/about", { locale: "es" }),
  href("/blog/[slug]", { slug: "hello", locale: "en" }),
  href("/blog/[slug]", { slug: "hello" }),
];
// @ts-expect-error not a configured locale
href("/about", { locale: "fr" });
// @ts-expect-error params are still required
href("/blog/[slug]", { locale: "es" });
`;

const MIDDLEWARE_USAGE = `import type { LayoutProps, Middleware, RequestContext, Routes } from "lumiose";

type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;
export type Assert<T extends true> = T;

type Ctx<M> = M extends (ctx: infer C, next: any) => any ? C : never;
type Shop = Ctx<Middleware<"/shop/[category]">>;
export type ShopParams = Assert<Equal<Shop["params"], { category: string }>>;
export type ShopRoute = Assert<Equal<Shop["route"], "/shop/[category]/[item]">>;
// A group folder's scope covers every route below its URL.
export type RootRoute = Assert<Equal<Ctx<Middleware<"/">>["route"], Routes>>;
// src/middleware.ts also runs for unmatched URLs.
export type AppRoute = Assert<Equal<Ctx<Middleware>["route"], Routes | undefined>>;
export type EndpointRoute = Assert<Equal<RequestContext<"/api/posts/[id]">["route"], "/api/posts/[id]">>;
export type ShopLayout = Assert<Equal<LayoutProps<"/shop/[category]">["params"], { category: string }>>;

export const guard: Middleware<"/shop/[category]"> = (ctx, next) => {
  const category: string = ctx.params.category;
  // @ts-expect-error the folder's params only
  ctx.params.item;
  return category === "" ? Promise.resolve(new Response(null, { status: 404 })) : next();
};
// @ts-expect-error not a folder with a layout or middleware
export type Unknown = Middleware<"/shop">;
`;

