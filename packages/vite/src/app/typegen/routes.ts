// Generates `.lumiose/types/routes.d.ts`: augments the `RouteMap` and `LayoutMap` registries in
// "lumiose" so `Routes`, `RouteParams`, `PageProps`, `LayoutProps`, `Middleware`, the request
// context types and `href()` know every route pattern (decision-26 §1).

import type { RouteManifest, RouteParam } from "lumiose/internal/app/routes/manifest.ts";

export function generateRouteTypes(
  manifest: Pick<RouteManifest, "routes" | "routesDir" | "layouts" | "middleware" | "i18n">,
): string {
  const routes = manifest.routes
    .toSorted((a, b) => compare(a.pattern, b.pattern))
    .map(
      (route) =>
        `    ${JSON.stringify(route.pattern)}: { kind: "${route.kind}"; params: ${paramsType(route.params)} };`,
    );
  // Folder scopes: `LayoutProps` and `Middleware` (decision-48) take them, so folders with only a
  // middleware file count too.
  const layouts = [
    ...new Set([...manifest.layouts, ...manifest.middleware].map((folder) => folder.pattern)),
  ]
    .toSorted(compare)
    .map(
      (pattern) =>
        `    ${JSON.stringify(pattern)}: { params: ${paramsType(patternParams(pattern))} };`,
    );
  return [
    `// Generated by Lumiose from ${manifest.routesDir}. Do not edit: \`lumiose typegen\` rewrites it.`,
    "export {};",
    "",
    'declare module "lumiose" {',
    "  interface RouteMap {",
    ...routes,
    "  }",
    "  interface LayoutMap {",
    ...layouts,
    "  }",
    // The `Locale` type of `lumiose({ i18n })` (decision-44).
    ...(manifest.i18n === undefined
      ? []
      : [
          "  interface LocaleMap {",
          ...manifest.i18n.locales.map((locale) => `    ${JSON.stringify(locale)}: true;`),
          "  }",
        ]),
    "}",
    "",
  ].join("\n");
}

/** `{ slug: string; lang?: string }`: an optional `[[param]]` may be absent. */
function paramsType(params: readonly Pick<RouteParam, "name" | "optional">[]): string {
  if (params.length === 0) return "{}";
  return `{ ${params.map(({ name, optional }) => `${name}${optional ? "?" : ""}: string`).join("; ")} }`;
}

/** `/[[lang]]/books/[isbn]/[...rest]` → `lang` (optional), `isbn`, `rest`. */
function patternParams(pattern: string): Pick<RouteParam, "name" | "optional">[] {
  return [...pattern.matchAll(/\[(\[)?(?:\.\.\.)?([^[\]]+)\]\]?/g)].map((match) => ({
    name: match[2]!,
    optional: match[1] !== undefined,
  }));
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}
